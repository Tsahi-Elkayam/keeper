using System.Text;
using System.Text.Json.Nodes;
using System.Text.RegularExpressions;
using YamlDotNet.RepresentationModel;

namespace Keeper.Review.Config;

/// <summary>
/// One integration as the config file records it - how Keeper reaches one system. This is the NON-SECRET
/// configuration only: the columns <c>integrations.upsert</c> writes (id, type, endpoint, auth kind, identity,
/// enabled, non-secret options), plus the NAMES of the secrets the integration expects. A secret's value - its
/// plaintext or its sealed ciphertext - is NEVER part of this record and never reaches the file; secrets are set
/// out of band with <c>keeper integration set-secret</c>. <see cref="Secrets"/> is presence and name only.
/// </summary>
public sealed record IntegrationRecord(
    string Id,
    string Type,
    string Endpoint,
    string AuthKind,
    string? Identity,
    bool Enabled,
    JsonObject Options,
    IReadOnlyList<string> Secrets);

/// <summary>
/// Reads and writes the integrations configuration file (schema <c>keeper.config/1</c>), mirroring SystemsConfig:
/// a deterministic writer (integrations ordered by id, option keys ordered, UTF-8) so export, import and a second
/// export are byte-for-byte the same, and parsing that refuses anchors, unknown fields and duplicates and reports
/// every problem as file:line:column. Secrets are written as names only - the security guarantee of this family.
/// </summary>
public static partial class IntegrationsConfig
{
    public const string Schema = ConfigYaml.Schema;

    private static readonly string[] TopFields = ["schema", "client", "integrations"];
    private static readonly string[] IntegrationFields =
        ["id", "type", "endpoint", "auth", "identity", "enabled", "options", "secrets"];

    /// <summary>The integrations in <paramref name="integrations"/>, ordered by id, as a config file's text.</summary>
    public static string Write(string? client, IReadOnlyList<IntegrationRecord> integrations)
    {
        var sb = new StringBuilder();
        sb.Append("# Client configuration - integrations (how Keeper reaches each system). NON-SECRET config only:\n");
        sb.Append("# a secret's NAME is recorded, never its value or ciphertext. Set secrets out of band with\n");
        sb.Append("# 'keeper integration set-secret'. Generated by 'keeper config export integrations'. Tenant data: never in the repo.\n");
        sb.Append("schema: ").Append(Schema).Append('\n');
        if (client is not null)
            sb.Append("client: ").Append(ConfigYaml.Quote(client)).Append('\n');

        if (integrations.Count == 0)
        {
            sb.Append("integrations: []\n");
            return sb.ToString();
        }

        sb.Append("integrations:\n");
        foreach (var i in integrations.OrderBy(i => i.Id, StringComparer.Ordinal))
        {
            sb.Append("  - id: ").Append(ConfigYaml.Quote(i.Id)).Append('\n');
            sb.Append("    type: ").Append(ConfigYaml.Quote(i.Type)).Append('\n');
            sb.Append("    endpoint: ").Append(ConfigYaml.Quote(i.Endpoint)).Append('\n');
            sb.Append("    auth: ").Append(ConfigYaml.Quote(i.AuthKind)).Append('\n');
            if (i.Identity is not null)
                sb.Append("    identity: ").Append(ConfigYaml.Quote(i.Identity)).Append('\n');
            sb.Append("    enabled: ").Append(i.Enabled ? "true" : "false").Append('\n');

            var options = Normalize(i.Options);
            if (options.Count > 0)
            {
                sb.Append("    options:\n");
                WriteMapping(sb, options, 6);
            }

            if (i.Secrets.Count > 0)
            {
                // Presence and name only - ordered, and each a quoted scalar. No value is ever written here.
                var names = i.Secrets.Order(StringComparer.Ordinal).Select(ConfigYaml.Quote);
                sb.Append("    secrets: [").Append(string.Join(", ", names)).Append("]\n");
            }
        }
        return sb.ToString();
    }

    private static void WriteMapping(StringBuilder sb, JsonObject map, int indent)
    {
        var pad = new string(' ', indent);
        foreach (var (key, value) in map.OrderBy(p => p.Key, StringComparer.Ordinal))
        {
            switch (value)
            {
                case JsonObject child when child.Count > 0:
                    sb.Append(pad).Append(key).Append(":\n");
                    WriteMapping(sb, child, indent + 2);
                    break;
                case JsonObject:
                    sb.Append(pad).Append(key).Append(": {}\n");
                    break;
                case JsonArray array when array.Count > 0:
                    sb.Append(pad).Append(key).Append(":\n");
                    WriteSequence(sb, array, indent + 2);
                    break;
                case JsonArray:
                    sb.Append(pad).Append(key).Append(": []\n");
                    break;
                default:
                    sb.Append(pad).Append(key).Append(": ").Append(ConfigYaml.Quote(Scalar(value))).Append('\n');
                    break;
            }
        }
    }

    private static void WriteSequence(StringBuilder sb, JsonArray array, int indent)
    {
        var pad = new string(' ', indent);
        foreach (var item in array)
        {
            switch (item)
            {
                case JsonObject child when child.Count > 0:
                    sb.Append(pad).Append("-\n");
                    WriteMapping(sb, child, indent + 4);
                    break;
                case JsonArray inner when inner.Count > 0:
                    sb.Append(pad).Append("-\n");
                    WriteSequence(sb, inner, indent + 4);
                    break;
                default:
                    sb.Append(pad).Append("- ").Append(ConfigYaml.Quote(Scalar(item))).Append('\n');
                    break;
            }
        }
    }

    /// <summary>
    /// The integrations a config file declares. <paramref name="source"/> is the name shown in errors (usually
    /// the path). Throws <see cref="ConfigException"/> if the file is malformed. No secret value is read: the
    /// file never carries one.
    /// </summary>
    public static IReadOnlyList<IntegrationRecord> Read(string text, string source, out string? client)
    {
        var errors = new List<string>();
        client = null;

        var root = ConfigYaml.Load(text, source);
        var top = ConfigYaml.Fields(root, "file", TopFields, source, errors);
        if (top is null)
            throw new ConfigException(errors);
        ConfigYaml.SchemaAndClient(top, source, errors, out client);

        var integrations = new List<IntegrationRecord>();
        var ids = new HashSet<string>(StringComparer.Ordinal);
        if (!top.TryGetValue("integrations", out var node))
        {
            errors.Add($"{source}: 'integrations' is required.");
        }
        else if (node is YamlSequenceNode sequence)
        {
            foreach (var item in sequence.Children)
            {
                var record = ReadIntegration(item, source, errors);
                if (record is null)
                    continue;
                if (!ids.Add(record.Id))
                    ConfigYaml.Error(item, source, errors, $"integration id '{record.Id}' appears more than once.");
                else
                    integrations.Add(record);
            }
        }
        else if (node is not YamlScalarNode { Value: null })
        {
            ConfigYaml.Error(node, source, errors, "'integrations' must be a list.");
        }

        if (errors.Count > 0)
            throw new ConfigException(errors);
        return integrations;
    }

    private static IntegrationRecord? ReadIntegration(YamlNode node, string source, List<string> errors)
    {
        var fields = ConfigYaml.Fields(node, "integration", IntegrationFields, source, errors);
        if (fields is null)
            return null;

        var id = ConfigYaml.Text(fields, "id", "integration", required: true, source, errors);
        if (id is not null && !IsIntegrationId(id))
        {
            ConfigYaml.Error(fields["id"], source, errors, "id must be lower-case letters, digits and dashes, starting with a letter (at most 60).");
            id = null;
        }
        var type = ConfigYaml.Text(fields, "type", "integration", required: true, source, errors);
        var authKind = ConfigYaml.Text(fields, "auth", "integration", required: true, source, errors);
        var endpoint = ConfigYaml.Text(fields, "endpoint", "integration", required: false, source, errors) ?? "";
        var identity = ConfigYaml.Text(fields, "identity", "integration", required: false, source, errors);

        var enabled = true;
        if (fields.TryGetValue("enabled", out var enabledNode))
        {
            if (enabledNode is YamlScalarNode { Value: "true" or "false" } b)
                enabled = b.Value == "true";
            else
                ConfigYaml.Error(enabledNode, source, errors, "enabled must be true or false.");
        }

        var options = new JsonObject();
        if (fields.TryGetValue("options", out var optionsNode) && optionsNode is not YamlScalarNode { Value: null })
        {
            if (optionsNode is YamlMappingNode)
                options = ReadMapping(optionsNode, source, errors);
            else
                ConfigYaml.Error(optionsNode, source, errors, "options must be a mapping of name to value.");
        }

        var secrets = ReadSecrets(fields, source, errors);

        if (id is null || type is null || authKind is null)
            return null;
        return new IntegrationRecord(id, type, endpoint, authKind, identity, enabled, Normalize(options), secrets);
    }

    private static List<string> ReadSecrets(Dictionary<string, YamlNode> fields, string source, List<string> errors)
    {
        var secrets = new List<string>();
        if (!fields.TryGetValue("secrets", out var node) || node is YamlScalarNode { Value: null })
            return secrets;
        if (node is not YamlSequenceNode sequence)
        {
            ConfigYaml.Error(node, source, errors, "secrets must be a list of secret names (values are never stored in the file).");
            return secrets;
        }
        var seen = new HashSet<string>(StringComparer.Ordinal);
        foreach (var item in sequence.Children)
        {
            if (item is not YamlScalarNode { Value: { } name } || name.Length == 0)
            {
                ConfigYaml.Error(item, source, errors, "a secret entry must be a name.");
                continue;
            }
            if (!seen.Add(name))
                ConfigYaml.Error(item, source, errors, $"secret name '{name}' appears more than once.");
            else
                secrets.Add(name);
        }
        return secrets;
    }

    private static JsonObject ReadMapping(YamlNode node, string source, List<string> errors)
    {
        var result = new JsonObject();
        if (node is not YamlMappingNode map)
        {
            ConfigYaml.Error(node, source, errors, "options must be a mapping of name to value.");
            return result;
        }
        foreach (var (key, value) in map.Children)
        {
            if (key is not YamlScalarNode { Value: { } name })
            {
                ConfigYaml.Error(key, source, errors, "option keys must be plain words.");
                continue;
            }
            if (result.ContainsKey(name))
            {
                ConfigYaml.Error(key, source, errors, $"option '{name}' appears twice.");
                continue;
            }
            result[name] = ReadValue(value, source, errors);
        }
        return result;
    }

    private static JsonNode? ReadValue(YamlNode node, string source, List<string> errors) => node switch
    {
        YamlMappingNode => ReadMapping(node, source, errors),
        YamlSequenceNode sequence => ReadArray(sequence, source, errors),
        YamlScalarNode scalar => JsonValue.Create(scalar.Value ?? ""),
        _ => JsonValue.Create(""),
    };

    private static JsonArray ReadArray(YamlSequenceNode sequence, string source, List<string> errors)
    {
        var array = new JsonArray();
        foreach (var item in sequence.Children)
            array.Add(ReadValue(item, source, errors));
        return array;
    }

    /// <summary>
    /// True when two records write the same integration configuration: id and every non-secret field equal, with
    /// options compared canonically. Secrets are not part of this - they live in a separate table, set out of band.
    /// </summary>
    public static bool SameConfig(IntegrationRecord a, IntegrationRecord b) =>
        string.Equals(a.Id, b.Id, StringComparison.Ordinal)
        && string.Equals(a.Type, b.Type, StringComparison.Ordinal)
        && string.Equals(a.Endpoint, b.Endpoint, StringComparison.Ordinal)
        && string.Equals(a.AuthKind, b.AuthKind, StringComparison.Ordinal)
        && string.Equals(a.Identity, b.Identity, StringComparison.Ordinal)
        && a.Enabled == b.Enabled
        && string.Equals(Canonical(a.Options), Canonical(b.Options), StringComparison.Ordinal);

    /// <summary>The options as canonical JSON: keys ordered, scalars as strings - the stable form the store keeps.</summary>
    public static string Canonical(JsonObject options) => Normalize(options).ToJsonString();

    /// <summary>
    /// A fresh copy with object keys ordered and every scalar coerced to a string - the shape the integration
    /// store and the config file both hold, so round-trips are byte-stable and comparisons are exact. The store
    /// only ever holds string, array-of-string and nested-object option values, so this changes nothing in practice.
    /// </summary>
    public static JsonObject Normalize(JsonObject options) => (JsonObject)NormalizeNode(options)!;

    private static JsonNode? NormalizeNode(JsonNode? node) => node switch
    {
        JsonObject o => new JsonObject(o.OrderBy(p => p.Key, StringComparer.Ordinal)
            .Select(p => KeyValuePair.Create(p.Key, NormalizeNode(p.Value)))),
        JsonArray a => new JsonArray(a.Select(NormalizeNode).ToArray()),
        JsonValue v => JsonValue.Create(Scalar(v)),
        _ => JsonValue.Create(""),
    };

    /// <summary>A JSON scalar node's text: the string itself, or true/false/the number as written.</summary>
    private static string Scalar(JsonNode? node) =>
        node is JsonValue v && v.TryGetValue<string>(out var s) ? s : node?.ToJsonString() ?? "";

    private static bool IsIntegrationId(string id) => id.Length <= 60 && IntegrationId().IsMatch(id);

    [GeneratedRegex("^[a-z][a-z0-9-]*$", RegexOptions.CultureInvariant)]
    private static partial Regex IntegrationId();
}
