using System.Globalization;
using System.Text;
using Keeper.Review.Handlers;
using YamlDotNet.RepresentationModel;

namespace Keeper.Review.Config;

/// <summary>
/// One register row as the config file records it: its id and the columns its <c>review.&lt;register&gt;</c>
/// upsert writes, normalised to the CLR types the store keeps (whole numbers as <see cref="long"/>, numbers as
/// <see cref="double"/>, booleans as 0/1 longs, everything else as text or null) so a record read from the file
/// and one built from a store row compare equal exactly when no write is needed.
/// </summary>
public sealed record RegisterRecord(string Id, IReadOnlyDictionary<string, object?> Columns);

/// <summary>
/// The latest attestation per obligation and target, as the config file records it. Append-only in the store,
/// so <see cref="Identity"/> is its full content: an import inserts one only when no identical row exists.
/// </summary>
public sealed record AttestationRecord(string Obligation, string Target, string State, string? DoneOn, string Evidence, string? ExpiresOn)
{
    public (string, string, string, string?, string, string?) Identity => (Obligation, Target, State, DoneOn, Evidence, ExpiresOn);
}

/// <summary>Everything the registers file holds: the rows of each register table, and the attestations.</summary>
public sealed record RegisterData(
    IReadOnlyDictionary<string, IReadOnlyList<RegisterRecord>> Tables,
    IReadOnlyList<AttestationRecord> Attestations);

/// <summary>
/// Reads and writes the registers configuration file (schema <c>keeper.config/1</c>), mirroring SystemsConfig:
/// one document with a section per register type (vendors, contracts, licences, key dates, initiatives) and
/// attestations. The writer is deterministic - rows ordered by id, a field only when it differs from its
/// default, numbers culture-free - so export, import and a second export are byte-for-byte the same. The fields
/// of each register come from its <see cref="RegisterSpec"/>, so the file and the store never drift.
/// </summary>
public static class RegistersConfig
{
    public const string Schema = ConfigYaml.Schema;

    private const string AttestationSection = "attestations";
    private static readonly string[] AttestationFields = ["obligation", "target", "state", "doneOn", "evidence", "expiresOn"];
    private static readonly string[] States = ["yes", "no", "na"];

    /// <summary>Each register and the section that holds it in the file, in the order they are written.</summary>
    public static readonly IReadOnlyList<(RegisterSpec Spec, string Section)> Sections =
    [
        (Registers.Vendor, "vendors"),
        (Registers.Contract, "contracts"),
        (Registers.Licence, "licences"),
        (Registers.KeyDate, "keyDates"),
        (Registers.Initiative, "initiatives"),
    ];

    private static readonly string[] TopFields =
        [.. new[] { "schema", "client" }, .. Sections.Select(s => s.Section), AttestationSection];

    /// <summary>The registers in <paramref name="data"/>, each section's rows ordered by id, as a file's text.</summary>
    public static string Write(string? client, RegisterData data)
    {
        var sb = new StringBuilder();
        sb.Append("# Client configuration - the registers rules read (vendors, contracts, licences, key dates,\n");
        sb.Append("# initiatives) and attestations. The record: this file is the source of truth, keeper.db caches\n");
        sb.Append("# it. Generated by 'keeper config export registers'. Tenant data: never in the repo.\n");
        sb.Append("schema: ").Append(Schema).Append('\n');
        if (client is not null)
            sb.Append("client: ").Append(ConfigYaml.Quote(client)).Append('\n');

        foreach (var (spec, section) in Sections)
        {
            var rows = data.Tables.TryGetValue(spec.Table, out var list) ? list : [];
            if (rows.Count == 0)
            {
                sb.Append(section).Append(": []\n");
                continue;
            }
            sb.Append(section).Append(":\n");
            foreach (var row in rows.OrderBy(r => r.Id, StringComparer.Ordinal))
            {
                sb.Append("  - id: ").Append(ConfigYaml.Quote(row.Id)).Append('\n');
                foreach (var field in spec.Fields)
                {
                    var value = row.Columns.GetValueOrDefault(field.Column);
                    // Written only when it differs from the default an absent field would take, so re-reading it
                    // rebuilds the same value and the file stays byte-stable. A null column always takes a null
                    // default (only nullable columns are ever null), so it is omitted either way.
                    if (value is null || Equals(value, DefaultValue(field)))
                        continue;
                    sb.Append("    ").Append(field.Name).Append(": ").Append(Scalar(field, value)).Append('\n');
                }
            }
        }

        if (data.Attestations.Count == 0)
        {
            sb.Append(AttestationSection).Append(": []\n");
            return sb.ToString();
        }
        sb.Append(AttestationSection).Append(":\n");
        foreach (var a in data.Attestations
            .OrderBy(a => a.Obligation, StringComparer.Ordinal).ThenBy(a => a.Target, StringComparer.Ordinal))
        {
            // obligation is a validated lower-case identifier - safe as a plain scalar.
            sb.Append("  - obligation: ").Append(a.Obligation).Append('\n');
            sb.Append("    target: ").Append(ConfigYaml.Quote(a.Target)).Append('\n');
            sb.Append("    state: ").Append(a.State).Append('\n');
            if (a.DoneOn is not null)
                sb.Append("    doneOn: ").Append(ConfigYaml.Quote(a.DoneOn)).Append('\n');
            sb.Append("    evidence: ").Append(ConfigYaml.Quote(a.Evidence)).Append('\n');
            if (a.ExpiresOn is not null)
                sb.Append("    expiresOn: ").Append(ConfigYaml.Quote(a.ExpiresOn)).Append('\n');
        }
        return sb.ToString();
    }

    /// <summary>
    /// The registers a config file declares. <paramref name="source"/> is the name shown in errors (usually the
    /// path). Throws <see cref="ConfigException"/> if the file is malformed.
    /// </summary>
    public static RegisterData Read(string text, string source, out string? client)
    {
        var errors = new List<string>();
        client = null;

        var root = ConfigYaml.Load(text, source);
        var top = ConfigYaml.Fields(root, "file", TopFields, source, errors);
        if (top is null)
            throw new ConfigException(errors);
        ConfigYaml.SchemaAndClient(top, source, errors, out client);

        var tables = new Dictionary<string, IReadOnlyList<RegisterRecord>>(StringComparer.Ordinal);
        foreach (var (spec, section) in Sections)
            tables[spec.Table] = ReadSection(top, section, spec, source, errors);

        var attestations = ReadAttestations(top, source, errors);

        if (errors.Count > 0)
            throw new ConfigException(errors);
        return new RegisterData(tables, attestations);
    }

    private static List<RegisterRecord> ReadSection(
        Dictionary<string, YamlNode> top, string section, RegisterSpec spec, string source, List<string> errors)
    {
        var records = new List<RegisterRecord>();
        if (!top.TryGetValue(section, out var node) || node is YamlScalarNode { Value: null })
            return records;   // absent or an empty 'section:' - no rows.
        if (node is not YamlSequenceNode sequence)
        {
            ConfigYaml.Error(node, source, errors, $"'{section}' must be a list.");
            return records;
        }

        var allowed = new string[spec.Fields.Count + 1];
        allowed[0] = "id";
        for (var i = 0; i < spec.Fields.Count; i++)
            allowed[i + 1] = spec.Fields[i].Name;

        var ids = new HashSet<string>(StringComparer.Ordinal);
        foreach (var item in sequence.Children)
        {
            var fields = ConfigYaml.Fields(item, section, allowed, source, errors);
            if (fields is null)
                continue;
            var id = ConfigYaml.Text(fields, "id", section, required: true, source, errors);
            if (id is not null && !Identifiers.IsRecordId(id))
            {
                ConfigYaml.Error(fields["id"], source, errors, "id must be letters, digits, dots, dashes or underscores (at most 100).");
                id = null;
            }

            var columns = new Dictionary<string, object?>(StringComparer.Ordinal);
            foreach (var field in spec.Fields)
                columns[field.Column] = ReadField(fields, field, section, source, errors);

            if (id is null)
                continue;
            if (!ids.Add(id))
                ConfigYaml.Error(item, source, errors, $"{section}: id '{id}' appears more than once.");
            else
                records.Add(new RegisterRecord(id, columns));
        }
        return records;
    }

    private static object? ReadField(Dictionary<string, YamlNode> fields, RegisterField field, string what, string source, List<string> errors)
    {
        if (!fields.ContainsKey(field.Name))
        {
            if (field.Required)
                errors.Add($"{source}: {what} is missing '{field.Name}'.");
            return DefaultValue(field);
        }

        switch (field.Type)
        {
            case FieldType.Text:
                var text = ConfigYaml.Text(fields, field.Name, what, required: false, source, errors);
                if (text is not null && text.Length > 2000)
                {
                    ConfigYaml.Error(fields[field.Name], source, errors, $"'{field.Name}' is at most 2000 characters.");
                    return null;
                }
                return text;
            case FieldType.Date:
                var date = ConfigYaml.Text(fields, field.Name, what, required: false, source, errors);
                if (date is not null && !DateOnly.TryParseExact(date, "yyyy-MM-dd", CultureInfo.InvariantCulture, DateTimeStyles.None, out _))
                {
                    ConfigYaml.Error(fields[field.Name], source, errors, $"'{field.Name}' must be a date (yyyy-MM-dd).");
                    return null;
                }
                return date;
            case FieldType.Int:
                return ConfigYaml.Integer(fields, field.Name, what, source, errors);
            case FieldType.Real:
                return ConfigYaml.Real(fields, field.Name, what, source, errors);
            case FieldType.Bool:
                return ConfigYaml.Boolean(fields, field.Name, what, source, errors) switch { true => 1L, false => 0L, null => 0L };
            case FieldType.Choice:
                var choice = ConfigYaml.Text(fields, field.Name, what, required: false, source, errors);
                if (choice is not null && !field.Choices!.Contains(choice, StringComparer.Ordinal))
                {
                    ConfigYaml.Error(fields[field.Name], source, errors, $"'{field.Name}' must be one of: {string.Join(", ", field.Choices!)}.");
                    return null;
                }
                return choice;
            default:
                return null;
        }
    }

    private static List<AttestationRecord> ReadAttestations(Dictionary<string, YamlNode> top, string source, List<string> errors)
    {
        var records = new List<AttestationRecord>();
        if (!top.TryGetValue(AttestationSection, out var node) || node is YamlScalarNode { Value: null })
            return records;
        if (node is not YamlSequenceNode sequence)
        {
            ConfigYaml.Error(node, source, errors, $"'{AttestationSection}' must be a list.");
            return records;
        }

        var seen = new HashSet<(string, string, string, string?, string, string?)>();
        foreach (var item in sequence.Children)
        {
            var fields = ConfigYaml.Fields(item, "attestation", AttestationFields, source, errors);
            if (fields is null)
                continue;

            var obligation = ConfigYaml.Text(fields, "obligation", "attestation", required: true, source, errors);
            if (obligation is not null && !Identifiers.IsValid(obligation))
            {
                ConfigYaml.Error(fields["obligation"], source, errors, "obligation must be lower-case letters, digits, dots and dashes (at most 100).");
                obligation = null;
            }
            var target = ConfigYaml.Text(fields, "target", "attestation", required: false, source, errors) ?? "-";
            var state = ConfigYaml.Text(fields, "state", "attestation", required: true, source, errors);
            if (state is not null && !States.Contains(state, StringComparer.Ordinal))
            {
                ConfigYaml.Error(fields["state"], source, errors, $"state must be one of: {string.Join(", ", States)}.");
                state = null;
            }
            var evidence = ConfigYaml.Text(fields, "evidence", "attestation", required: true, source, errors);

            var doneOn = ReadDate(fields, "doneOn", source, errors);
            var expiresOn = ReadDate(fields, "expiresOn", source, errors);

            if (obligation is null || state is null || evidence is null)
                continue;
            var record = new AttestationRecord(obligation, target, state, doneOn, evidence, expiresOn);
            if (!seen.Add(record.Identity))
                ConfigYaml.Error(item, source, errors, $"attestation '{obligation}' for '{target}' appears more than once.");
            else
                records.Add(record);
        }
        return records;
    }

    private static string? ReadDate(Dictionary<string, YamlNode> fields, string name, string source, List<string> errors)
    {
        var text = ConfigYaml.Text(fields, name, "attestation", required: false, source, errors);
        if (text is not null && !DateOnly.TryParseExact(text, "yyyy-MM-dd", CultureInfo.InvariantCulture, DateTimeStyles.None, out _))
        {
            ConfigYaml.Error(fields[name], source, errors, $"'{name}' must be a date (yyyy-MM-dd).");
            return null;
        }
        return text;
    }

    /// <summary>The value an absent field takes - the register handler's own default, normalised to a store type.</summary>
    public static object? DefaultValue(RegisterField field) => field.Default switch
    {
        long l => l,
        string s => s,
        _ => field.Type == FieldType.Bool ? 0L : null,
    };

    /// <summary>True when two records would write the same row - id and every register column equal.</summary>
    public static bool Same(RegisterSpec spec, RegisterRecord a, RegisterRecord b)
    {
        if (!string.Equals(a.Id, b.Id, StringComparison.Ordinal))
            return false;
        foreach (var field in spec.Fields)
        {
            if (!Equals(a.Columns.GetValueOrDefault(field.Column), b.Columns.GetValueOrDefault(field.Column)))
                return false;
        }
        return true;
    }

    private static string Scalar(RegisterField field, object value) => field.Type switch
    {
        FieldType.Int => ((long)value).ToString(CultureInfo.InvariantCulture),
        FieldType.Real => ConfigYaml.Number((double)value),
        FieldType.Bool => (long)value == 1L ? "true" : "false",
        _ => ConfigYaml.Quote((string)value),
    };
}
