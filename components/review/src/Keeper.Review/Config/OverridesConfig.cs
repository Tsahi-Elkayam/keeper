using System.Globalization;
using System.Text;
using YamlDotNet.RepresentationModel;

namespace Keeper.Review.Config;

/// <summary>
/// One active override as the config file records it - the decision a person made about a rule: disable it,
/// change its threshold, or accept one entity as an exception, optionally until a date. The file models the
/// desired ACTIVE state; <see cref="Identity"/> is what makes two overrides the same decision (reason aside),
/// so an import adds only the ones not already active.
/// </summary>
public sealed record OverrideRecord(string CheckId, string Decision, string Entity, string Value, string? Until, string Reason)
{
    /// <summary>What distinguishes one active decision from another - the reason is audit, not identity.</summary>
    public (string, string, string, string, string?) Identity => (CheckId, Decision, Entity, Value, Until);
}

/// <summary>
/// Reads and writes the overrides configuration file (schema <c>keeper.config/1</c>), mirroring SystemsConfig:
/// deterministic writer (overrides ordered by their identity, UTF-8), parsing that refuses anchors, unknown
/// fields and duplicates and reports every problem as file:line:column. The decision validations match
/// <c>review.override</c>: disable takes no entity, exception needs one, threshold needs a value.
/// </summary>
public static class OverridesConfig
{
    public const string Schema = ConfigYaml.Schema;

    private static readonly string[] TopFields = ["schema", "client", "overrides"];
    private static readonly string[] OverrideFields = ["checkId", "decision", "entity", "value", "until", "reason"];
    private static readonly string[] Decisions = ["disable", "threshold", "exception"];

    /// <summary>The overrides in <paramref name="overrides"/>, ordered by identity, as a config file's text.</summary>
    public static string Write(string? client, IReadOnlyList<OverrideRecord> overrides)
    {
        var sb = new StringBuilder();
        sb.Append("# Client configuration - active overrides (disable / threshold / exception decisions). The record:\n");
        sb.Append("# this file is the source of truth, keeper.db caches it. Generated by 'keeper config export overrides'.\n");
        sb.Append("schema: ").Append(Schema).Append('\n');
        if (client is not null)
            sb.Append("client: ").Append(ConfigYaml.Quote(client)).Append('\n');

        if (overrides.Count == 0)
        {
            sb.Append("overrides: []\n");
            return sb.ToString();
        }

        sb.Append("overrides:\n");
        foreach (var o in overrides
            .OrderBy(o => o.CheckId, StringComparer.Ordinal).ThenBy(o => o.Decision, StringComparer.Ordinal)
            .ThenBy(o => o.Entity, StringComparer.Ordinal).ThenBy(o => o.Value, StringComparer.Ordinal)
            .ThenBy(o => o.Until, StringComparer.Ordinal))
        {
            sb.Append("  - checkId: ").Append(ConfigYaml.Quote(o.CheckId)).Append('\n');
            // decision is one of three lower-case words - safe as a plain scalar.
            sb.Append("    decision: ").Append(o.Decision).Append('\n');
            if (o.Entity.Length > 0)
                sb.Append("    entity: ").Append(ConfigYaml.Quote(o.Entity)).Append('\n');
            if (o.Value.Length > 0)
                sb.Append("    value: ").Append(ConfigYaml.Quote(o.Value)).Append('\n');
            if (o.Until is not null)
                sb.Append("    until: ").Append(ConfigYaml.Quote(o.Until)).Append('\n');
            sb.Append("    reason: ").Append(ConfigYaml.Quote(o.Reason)).Append('\n');
        }
        return sb.ToString();
    }

    /// <summary>
    /// The overrides a config file declares. <paramref name="source"/> is the name shown in errors (usually the
    /// path). Throws <see cref="ConfigException"/> if the file is malformed.
    /// </summary>
    public static IReadOnlyList<OverrideRecord> Read(string text, string source, out string? client)
    {
        var errors = new List<string>();
        client = null;

        var root = ConfigYaml.Load(text, source);
        var top = ConfigYaml.Fields(root, "file", TopFields, source, errors);
        if (top is null)
            throw new ConfigException(errors);
        ConfigYaml.SchemaAndClient(top, source, errors, out client);

        var overrides = new List<OverrideRecord>();
        var seen = new HashSet<(string, string, string, string, string?)>();
        if (!top.TryGetValue("overrides", out var overridesNode))
        {
            errors.Add($"{source}: 'overrides' is required.");
        }
        else if (overridesNode is YamlSequenceNode sequence)
        {
            foreach (var node in sequence.Children)
            {
                var record = ReadOverride(node, source, errors);
                if (record is null)
                    continue;
                if (!seen.Add(record.Identity))
                    ConfigYaml.Error(node, source, errors, $"override '{record.CheckId}' ({record.Decision}) appears more than once.");
                else
                    overrides.Add(record);
            }
        }
        else if (overridesNode is not YamlScalarNode { Value: null })
        {
            ConfigYaml.Error(overridesNode, source, errors, "'overrides' must be a list.");
        }

        if (errors.Count > 0)
            throw new ConfigException(errors);
        return overrides;
    }

    private static OverrideRecord? ReadOverride(YamlNode node, string source, List<string> errors)
    {
        var fields = ConfigYaml.Fields(node, "override", OverrideFields, source, errors);
        if (fields is null)
            return null;

        var checkId = ConfigYaml.Text(fields, "checkId", "override", required: true, source, errors);
        var decision = ConfigYaml.Text(fields, "decision", "override", required: true, source, errors);
        if (decision is not null && !Decisions.Contains(decision, StringComparer.Ordinal))
        {
            ConfigYaml.Error(fields["decision"], source, errors, $"decision must be one of: {string.Join(", ", Decisions)}.");
            decision = null;
        }
        var entity = ConfigYaml.Text(fields, "entity", "override", required: false, source, errors) ?? "";
        var value = ConfigYaml.Text(fields, "value", "override", required: false, source, errors) ?? "";
        var reason = ConfigYaml.Text(fields, "reason", "override", required: true, source, errors);

        string? until = null;
        if (fields.TryGetValue("until", out var untilNode))
        {
            if (untilNode is YamlScalarNode { Value: { } untilText }
                && DateOnly.TryParseExact(untilText, "yyyy-MM-dd", CultureInfo.InvariantCulture, DateTimeStyles.None, out _))
                until = untilText;
            else
                ConfigYaml.Error(untilNode, source, errors, "until must be a date (yyyy-MM-dd).");
        }

        // The same shape checks review.override applies, so the file is refused here rather than at apply time.
        if (decision == "disable" && entity.Length > 0)
            ConfigYaml.Error(node, source, errors, "a disable override applies to the whole rule; leave entity empty.");
        if (decision == "exception" && entity.Length == 0)
            ConfigYaml.Error(node, source, errors, "an exception override needs an entity.");
        if (decision == "threshold" && value.Length == 0)
            ConfigYaml.Error(node, source, errors, "a threshold override needs a value.");

        // Any shape error above is already in the list, so Read throws; the record is only used for duplicate
        // detection in the meantime, which needs the identity fields.
        if (checkId is null || decision is null || reason is null)
            return null;
        return new OverrideRecord(checkId, decision, entity, value, until, reason);
    }
}
