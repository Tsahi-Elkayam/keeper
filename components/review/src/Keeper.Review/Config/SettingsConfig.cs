using System.Text;
using YamlDotNet.RepresentationModel;

namespace Keeper.Review.Config;

/// <summary>
/// One tenant setting as the config file records it - the columns <c>review.setting</c> upserts. A record read
/// from the file and one built from a store row compare equal exactly when no write is needed.
/// </summary>
public sealed record SettingRecord(string Key, string Value);

/// <summary>
/// Reads and writes the settings configuration file (schema <c>keeper.config/1</c>), mirroring SystemsConfig:
/// deterministic writer (settings ordered by key, UTF-8), parsing that refuses anchors, unknown fields and
/// duplicates and reports every problem as file:line:column.
/// </summary>
public static class SettingsConfig
{
    public const string Schema = ConfigYaml.Schema;

    private static readonly string[] TopFields = ["schema", "client", "settings"];
    private static readonly string[] SettingFields = ["key", "value"];

    /// <summary>The settings in <paramref name="settings"/>, ordered by key, as a config file's text.</summary>
    public static string Write(string? client, IReadOnlyList<SettingRecord> settings)
    {
        var sb = new StringBuilder();
        sb.Append("# Client configuration - tenant settings (thresholds and routing). The record: this file is the\n");
        sb.Append("# source of truth, keeper.db caches it. Generated by 'keeper config export settings'.\n");
        sb.Append("schema: ").Append(Schema).Append('\n');
        if (client is not null)
            sb.Append("client: ").Append(ConfigYaml.Quote(client)).Append('\n');

        if (settings.Count == 0)
        {
            sb.Append("settings: []\n");
            return sb.ToString();
        }

        sb.Append("settings:\n");
        foreach (var s in settings.OrderBy(s => s.Key, StringComparer.Ordinal))
        {
            // The key is a validated identifier (lower-case letters, digits, dots, dashes) - safe as a plain scalar.
            sb.Append("  - key: ").Append(s.Key).Append('\n');
            sb.Append("    value: ").Append(ConfigYaml.Quote(s.Value)).Append('\n');
        }
        return sb.ToString();
    }

    /// <summary>
    /// The settings a config file declares. <paramref name="source"/> is the name shown in errors (usually the
    /// path). Throws <see cref="ConfigException"/> if the file is malformed.
    /// </summary>
    public static IReadOnlyList<SettingRecord> Read(string text, string source, out string? client)
    {
        var errors = new List<string>();
        client = null;

        var root = ConfigYaml.Load(text, source);
        var top = ConfigYaml.Fields(root, "file", TopFields, source, errors);
        if (top is null)
            throw new ConfigException(errors);
        ConfigYaml.SchemaAndClient(top, source, errors, out client);

        var settings = new List<SettingRecord>();
        var keys = new HashSet<string>(StringComparer.Ordinal);
        if (!top.TryGetValue("settings", out var settingsNode))
        {
            errors.Add($"{source}: 'settings' is required.");
        }
        else if (settingsNode is YamlSequenceNode sequence)
        {
            foreach (var node in sequence.Children)
            {
                var record = ReadSetting(node, source, errors);
                if (record is null)
                    continue;
                if (!keys.Add(record.Key))
                    ConfigYaml.Error(node, source, errors, $"setting key '{record.Key}' appears more than once.");
                else
                    settings.Add(record);
            }
        }
        else if (settingsNode is not YamlScalarNode { Value: null })
        {
            ConfigYaml.Error(settingsNode, source, errors, "'settings' must be a list.");
        }

        if (errors.Count > 0)
            throw new ConfigException(errors);
        return settings;
    }

    private static SettingRecord? ReadSetting(YamlNode node, string source, List<string> errors)
    {
        var fields = ConfigYaml.Fields(node, "setting", SettingFields, source, errors);
        if (fields is null)
            return null;

        var key = ConfigYaml.Text(fields, "key", "setting", required: true, source, errors);
        if (key is not null && !Identifiers.IsValid(key))
        {
            ConfigYaml.Error(fields["key"], source, errors, "key must be lower-case letters, digits, dots and dashes (at most 100).");
            key = null;
        }
        var value = ConfigYaml.Text(fields, "value", "setting", required: true, source, errors);
        if (value is not null && value.Length > 500)
        {
            ConfigYaml.Error(fields["value"], source, errors, "value is at most 500 characters.");
            value = null;
        }

        if (key is null || value is null)
            return null;
        return new SettingRecord(key, value);
    }
}
