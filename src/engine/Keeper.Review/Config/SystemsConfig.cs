using System.Text;
using System.Text.RegularExpressions;
using YamlDotNet.Core;
using YamlDotNet.RepresentationModel;

namespace Keeper.Review.Config;

/// <summary>
/// One system as the config file records it. The file (systems.yaml) is the source of truth; the store's
/// <c>system</c> table is data plus a cache of it. These are the columns <c>review.system</c> upserts, so a
/// record read from the file and one built from a store row compare equal exactly when no write is needed.
/// </summary>
public sealed record SystemRecord(
    string Id,
    string Name,
    string? Owner,
    string? OwnerPerson,
    string? Purpose,
    string? Team,
    string? Route,
    int? Criticality,
    bool Active,
    string? Notes);

/// <summary>A config file could not be read. Each error carries file:line:column where it can.</summary>
public sealed class ConfigException(IReadOnlyList<string> errors)
    : Exception(string.Join(Environment.NewLine, errors))
{
    public IReadOnlyList<string> Errors { get; } = errors;
}

/// <summary>
/// Reads and writes the systems configuration file (schema <c>keeper.config/1</c>). The writer is
/// deterministic - systems ordered by id, a fixed field order, UTF-8 - so export, import and a second export
/// produce byte-for-byte the same file. Parsing reuses the engine's YAML library (YamlDotNet), refuses
/// anchors and unknown fields, and reports every problem with its position.
/// </summary>
public static partial class SystemsConfig
{
    public const string Schema = "keeper.config/1";

    private static readonly string[] TopFields = ["schema", "client", "systems"];
    private static readonly string[] SystemFields =
        ["id", "name", "owner", "ownerPerson", "purpose", "team", "route", "criticality", "active", "notes"];

    /// <summary>The systems in <paramref name="systems"/>, ordered by id, as a config file's text.</summary>
    public static string Write(string? client, IReadOnlyList<SystemRecord> systems)
    {
        var sb = new StringBuilder();
        sb.Append("# Client configuration - systems in scope. The record: this file is the source of truth,\n");
        sb.Append("# keeper.db caches it. Generated by 'keeper config export systems'. Tenant data: never in the repo.\n");
        sb.Append("schema: ").Append(Schema).Append('\n');
        if (client is not null)
            sb.Append("client: ").Append(Quote(client)).Append('\n');

        if (systems.Count == 0)
        {
            sb.Append("systems: []\n");
            return sb.ToString();
        }

        sb.Append("systems:\n");
        foreach (var s in systems.OrderBy(s => s.Id, StringComparer.Ordinal))
        {
            sb.Append("  - id: ").Append(Quote(s.Id)).Append('\n');
            sb.Append("    name: ").Append(Quote(s.Name)).Append('\n');
            Field(sb, "owner", s.Owner);
            Field(sb, "ownerPerson", s.OwnerPerson);
            Field(sb, "purpose", s.Purpose);
            Field(sb, "team", s.Team);
            if (s.Route is not null)
                sb.Append("    route: ").Append(Bareable(s.Route) ? s.Route : Quote(s.Route)).Append('\n');
            if (s.Criticality is { } crit)
                sb.Append("    criticality: ").Append(crit).Append('\n');
            sb.Append("    active: ").Append(s.Active ? "true" : "false").Append('\n');
            Field(sb, "notes", s.Notes);
        }
        return sb.ToString();

        static void Field(StringBuilder sb, string name, string? value)
        {
            if (value is not null)
                sb.Append("    ").Append(name).Append(": ").Append(Quote(value)).Append('\n');
        }
    }

    /// <summary>
    /// The systems a config file declares. <paramref name="source"/> is the name shown in errors (usually the
    /// path). Throws <see cref="ConfigException"/> if the file is malformed.
    /// </summary>
    public static IReadOnlyList<SystemRecord> Read(string text, string source, out string? client)
    {
        var errors = new List<string>();
        client = null;

        var yaml = new YamlStream();
        try
        {
            yaml.Load(new StringReader(text));
        }
        catch (YamlException ex)
        {
            throw new ConfigException([$"{source}:{ex.Start.Line}:{ex.Start.Column}: {ex.Message}"]);
        }
        catch (ArgumentException ex)
        {
            throw new ConfigException([$"{source}: {ex.Message}"]);
        }
        if (yaml.Documents.Count != 1)
            throw new ConfigException([$"{source}: must hold exactly one YAML document."]);

        RefuseAnchors(yaml.Documents[0].RootNode, source, errors);
        if (errors.Count > 0)
            throw new ConfigException(errors);

        var top = Fields(yaml.Documents[0].RootNode, "file", TopFields, source, errors);
        if (top is null)
            throw new ConfigException(errors);

        var schema = Text(top, "schema", "file", required: true, source, errors);
        if (schema is not null && schema != Schema)
            Error(top["schema"], source, errors, $"schema must be {Schema}.");
        client = Text(top, "client", "file", required: false, source, errors);

        var systems = new List<SystemRecord>();
        var ids = new HashSet<string>(StringComparer.Ordinal);
        if (!top.TryGetValue("systems", out var systemsNode))
        {
            errors.Add($"{source}: 'systems' is required.");
        }
        else if (systemsNode is YamlSequenceNode sequence)
        {
            foreach (var node in sequence.Children)
            {
                var record = ReadSystem(node, source, errors);
                if (record is null)
                    continue;
                if (!ids.Add(record.Id))
                    Error(node, source, errors, $"system id '{record.Id}' appears more than once.");
                else
                    systems.Add(record);
            }
        }
        else if (systemsNode is not YamlScalarNode { Value: null })
        {
            // A null scalar is an empty 'systems:' - allowed (no systems). Anything else must be a list.
            Error(systemsNode, source, errors, "'systems' must be a list.");
        }

        if (errors.Count > 0)
            throw new ConfigException(errors);
        return systems;
    }

    private static SystemRecord? ReadSystem(YamlNode node, string source, List<string> errors)
    {
        var fields = Fields(node, "system", SystemFields, source, errors);
        if (fields is null)
            return null;

        var id = Text(fields, "id", "system", required: true, source, errors);
        if (id is not null && !Identifiers.IsRecordId(id))
        {
            Error(fields["id"], source, errors, "id must be letters, digits, dots, dashes or underscores (at most 100).");
            id = null;
        }
        var name = Text(fields, "name", "system", required: true, source, errors);

        int? criticality = null;
        if (fields.TryGetValue("criticality", out var critNode))
        {
            if (critNode is YamlScalarNode { Value: { } critText }
                && int.TryParse(critText, System.Globalization.NumberStyles.None, System.Globalization.CultureInfo.InvariantCulture, out var crit)
                && crit is 1 or 2 or 3)
                criticality = crit;
            else
                Error(critNode, source, errors, "criticality must be 1, 2 or 3.");
        }

        var active = true;
        if (fields.TryGetValue("active", out var activeNode))
        {
            if (activeNode is YamlScalarNode { Value: "true" or "false" } boolean)
                active = boolean.Value == "true";
            else
                Error(activeNode, source, errors, "active must be true or false.");
        }

        if (id is null || name is null)
            return null;
        return new SystemRecord(
            id, name,
            Text(fields, "owner", "system", required: false, source, errors),
            Text(fields, "ownerPerson", "system", required: false, source, errors),
            Text(fields, "purpose", "system", required: false, source, errors),
            Text(fields, "team", "system", required: false, source, errors),
            Text(fields, "route", "system", required: false, source, errors),
            criticality, active,
            Text(fields, "notes", "system", required: false, source, errors));
    }

    private static Dictionary<string, YamlNode>? Fields(
        YamlNode? node, string what, IReadOnlyCollection<string> allowed, string source, List<string> errors)
    {
        if (node is not YamlMappingNode map)
        {
            if (node is not null)
                Error(node, source, errors, $"{what} must be a mapping.");
            return null;
        }
        var fields = new Dictionary<string, YamlNode>(StringComparer.Ordinal);
        foreach (var (key, value) in map.Children)
        {
            if (key is not YamlScalarNode { Value: { } name })
            {
                Error(key, source, errors, $"{what}: keys must be plain words.");
                continue;
            }
            if (!allowed.Contains(name))
            {
                Error(key, source, errors, $"{what}: unknown field '{name}'. Allowed: {string.Join(", ", allowed)}.");
                continue;
            }
            if (!fields.TryAdd(name, value))
                Error(key, source, errors, $"{what}: '{name}' appears twice.");
        }
        return fields;
    }

    private static string? Text(
        Dictionary<string, YamlNode> fields, string name, string what, bool required, string source, List<string> errors)
    {
        if (!fields.TryGetValue(name, out var node))
        {
            if (required)
                errors.Add($"{source}: {what} is missing '{name}'.");
            return null;
        }
        if (node is YamlScalarNode { Value: { } value })
            return value;
        Error(node, source, errors, $"{what}: '{name}' must be a single value.");
        return null;
    }

    private static void RefuseAnchors(YamlNode node, string source, List<string> errors)
    {
        if (!node.Anchor.IsEmpty)
        {
            Error(node, source, errors, "anchors and aliases are not allowed in config files.");
            return;
        }
        switch (node)
        {
            case YamlMappingNode map:
                foreach (var (key, value) in map.Children)
                {
                    RefuseAnchors(key, source, errors);
                    RefuseAnchors(value, source, errors);
                }
                break;
            case YamlSequenceNode sequence:
                foreach (var item in sequence.Children)
                    RefuseAnchors(item, source, errors);
                break;
        }
    }

    private static void Error(YamlNode node, string source, List<string> errors, string message) =>
        errors.Add($"{source}:{node.Start.Line}:{node.Start.Column}: {message}");

    /// <summary>A value safe to write without quotes - a plain lower-case word such as a route.</summary>
    private static bool Bareable(string value) => BareWord().IsMatch(value);

    /// <summary>
    /// Single-quoted (<c>''</c> escapes a quote) for the common one-line value, matching the proof file;
    /// double-quoted with escapes when the value holds a newline or tab, so every value round-trips.
    /// </summary>
    private static string Quote(string value)
    {
        if (value.IndexOfAny(['\n', '\r', '\t']) < 0)
            return "'" + value.Replace("'", "''") + "'";
        var sb = new StringBuilder("\"");
        foreach (var c in value)
            sb.Append(c switch
            {
                '\\' => "\\\\",
                '"' => "\\\"",
                '\n' => "\\n",
                '\r' => "\\r",
                '\t' => "\\t",
                _ => c.ToString(),
            });
        return sb.Append('"').ToString();
    }

    [GeneratedRegex("^[a-z][a-z0-9-]*$", RegexOptions.CultureInvariant)]
    private static partial Regex BareWord();
}
